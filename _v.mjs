import { chromium } from 'playwright';
import fs from 'node:fs';
const OUT='/tmp/claude-0/-home-user-Nadja-Makoie/cb853670-03ec-5223-b944-f49d62372839/scratchpad';
function fc(){const r=fs.readdirSync('/opt/pw-browsers').filter(d=>d.startsWith('chromium'));for(const x of r)for(const p of [`/opt/pw-browsers/${x}/chrome-linux/chrome`,`/opt/pw-browsers/${x}/chrome-linux/headless_shell`])if(fs.existsSync(p))return p;}
const errors=[];
const b=await chromium.launch({executablePath:fc()});
const c=await b.newContext({viewport:{width:1440,height:900}});
const tmp=await c.newPage();
