await tmp.close();
const buf=Buffer.from(tile.split(',')[1],'base64');
await c.route('**/images.higgs.ai/**',r=>r.fulfill({status:200,contentType:'image/png',body:buf}));
const p=await c.newPage();
p.on('pageerror',e=>errors.push('PAGEERROR: '+e.message));
await p.goto('http://localhost:4173/',{waitUntil:'networkidle'}).catch(()=>{});
await p.waitForTimeout(1000);
const hasIframe=await p.evaluate(()=>!!document.querySelector('#kontakt iframe'));
